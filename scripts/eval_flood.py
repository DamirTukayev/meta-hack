"""What does a map know that the flood has already made false? Measured on the Hurricane Harvey photo.

A navigator routes on the mapped streets (OpenStreetMap is the stand-in here: © OpenStreetMap contributors, ODbL, used
only as a yardstick, not part of the product). The photo shows the water. This counts how much of the mapped street
network lies under the standing water SAM 3.1 finds, and how much of that the road graph can see. Cached model answers
only: no paid calls. Writes eval/FLOOD.md and eval/flood.json.

Usage: uv run python scripts/eval_flood.py [sample]
"""

from __future__ import annotations

import json
import sys

import numpy as np
from PIL import Image, ImageDraw
from scipy.ndimage import distance_transform_edt

from orbitroute.config import ROOT, Settings
from orbitroute.llm.budget import BudgetGuard
from orbitroute.llm.client import MetaClient
from orbitroute.naip import to_mercator
from orbitroute.perception.flood import flood_zones, segment_floods
from orbitroute.perception.graph import build_road_graph
from orbitroute.perception.segment import segment_roads
from orbitroute.pipeline import get_sample

STREETS = {"motorway", "trunk", "primary", "secondary", "tertiary", "unclassified", "residential", "living_street"}
HIDDEN_SERVICE = {"parking_aisle", "driveway", "drive-through"}
TOL_M = 15


def analyse(name: str) -> dict:
    s = Settings.load()
    guard = BudgetGuard(s.budget_state_path, s.budget_hard_cap_usd, False)
    client = MetaClient(s, guard)
    sm = get_sample(name)
    W, H, mpp = sm.meta["width_px"], sm.meta["height_px"], sm.meta["m_per_px"]
    x0, y0, x1, y1 = sm.meta["bbox_mercator"]

    zones = flood_zones(segment_floods(client, sm.image_bytes, run=guard.new_run(1)), mpp)
    flood = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(flood)
    for z in zones:
        d.polygon(list(z.polygon.exterior.coords), fill=255)
    F = np.asarray(flood) > 0

    graph = build_road_graph(segment_roads(client, sm.image_bytes, run=guard.new_run(1)), mpp)
    g_im = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(g_im)
    for e in graph.edges:
        d.line([tuple(graph.nodes[e.u]), tuple(graph.nodes[e.v])], fill=255, width=1)
    G = np.asarray(g_im) > 0
    dist_to_graph = distance_transform_edt(~G) * mpp

    osm = json.loads((ROOT / "data" / "cache" / f"osm_{name}.json").read_text())

    def px(lon: float, lat: float) -> tuple[float, float]:
        x, y = to_mercator(lon, lat)
        return (x - x0) / (x1 - x0) * W, (y1 - y) / (y1 - y0) * H

    def raster(keep) -> np.ndarray:
        im = Image.new("L", (W, H), 0)
        dr = ImageDraw.Draw(im)
        for el in osm["elements"]:
            if "geometry" in el and keep(el.get("tags", {})):
                dr.line([px(p["lon"], p["lat"]) for p in el["geometry"]], fill=255, width=1)
        return np.asarray(im) > 0

    rows = []
    for label, keep in [
        ("named streets", lambda t: t.get("highway") in STREETS),
        ("streets + service roads (no parking aisles or driveways)", lambda t: t.get("highway") is not None and t.get("service") not in HIDDEN_SERVICE),
    ]:
        R = raster(keep)
        under = R & F
        rows.append(
            {
                "reference": label,
                "mapped_km": round(R.sum() * mpp / 1000, 2),
                "under_water_km": round(under.sum() * mpp / 1000, 2),
                "under_water_share": float(under.sum() / max(R.sum(), 1)),
                "seen_by_graph_when_under_water": float((dist_to_graph[under] <= TOL_M).mean()) if under.any() else None,
            }
        )
    graph_under = G & F
    out = {
        "sample": name,
        "flooded_share_of_photo": float(F.mean()),
        "flood_zones": len(zones),
        "graph_km": graph.stats["road_km"],
        "graph_under_water_km": round(graph_under.sum() * mpp / 1000, 2),
        "rows": rows,
    }
    return out


def main() -> None:
    names = sys.argv[1:] or ["houston-harvey", "houston-harvey-b"]
    results = [analyse(n) for n in names]
    (ROOT / "eval" / "flood.json").write_text(json.dumps(results, indent=1))
    lines = [
        "# Flood: what the map knows and the photo shows",
        "",
        "Generated by `scripts/eval_flood.py` on two Hurricane Harvey photos (NOAA Emergency Response Imagery, 30 Aug 2017, 1.5 km squares).",
        "OpenStreetMap stands in for \"the map a navigator works from\" (© OpenStreetMap contributors, ODbL; used only as a yardstick).",
        "The water is what SAM 3.1 finds on the photo (`flooded area` and `flood water`), enlarged by 6 m.",
        "",
    ]
    for out in results:
        lines += [
            f"## {out['sample']}",
            "",
            f"Standing water covers **{out['flooded_share_of_photo']:.0%}** of the photo in {out['flood_zones']} patches.",
            "",
            "| Streets in the map | Mapped length | Under water | Share under water | Of those, seen as road in the photo |",
            "|---|---|---|---|---|",
        ]
        for r in out["rows"]:
            seen = f"{r['seen_by_graph_when_under_water']:.0%}" if r["seen_by_graph_when_under_water"] is not None else "-"
            lines.append(f"| {r['reference']} | {r['mapped_km']} km | {r['under_water_km']} km | {r['under_water_share']:.0%} | {seen} |")
        lines += ["", f"The road graph the agent routes on is {out['graph_km']} km, of which {out['graph_under_water_km']} km lies inside the water zones; the solver is forbidden from using it.", ""]
    lines += [
        "Reading: a router that trusts the map would send trucks along the streets in the \"under water\" column, because nothing in the map says they are flooded. The photo does. The limit: where the water hides a street completely SAM cannot see it either, so those streets are simply missing from the graph (last column), and the agent avoids the water zones around them.",
        "",
        "Limits: two 1.5 km tiles; OSM is itself incomplete; the water outlines are SAM's, with no human labels, and muddy street water under trees is the hardest case.",
        "",
    ]
    (ROOT / "eval" / "FLOOD.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
