"""Does a second look at the bridged gaps find the roads that were missed? Measured on the four bundled photos.

The graph builder draws a straight link across every hole in the SAM road mask. `perception/gaps.py` sends a crop around
each long link to SAM again and keeps the link only as an unconfirmed guess when the closer look finds no road there. This
reports, per photo, how many long links there were, how many the second look confirmed, how many of the links lie on a
mapped road (OpenStreetMap, © OpenStreetMap contributors, ODbL; a yardstick only), and the recall and precision of the
graph before and after. About $0.0025 per link; answers are cached. Writes eval/GAPS.md and eval/gaps.json.

Usage: uv run python scripts/eval_gaps.py [sample ...]
"""

from __future__ import annotations

import json
import sys

import numpy as np
from PIL import Image, ImageDraw
from scipy.ndimage import distance_transform_edt

from orbitroute.config import ROOT, Settings
from orbitroute.llm.budget import BudgetGuard
from orbitroute.llm.client import MetaClient
from orbitroute.naip import to_mercator
from orbitroute.perception.gaps import MIN_LINK_M, fill_gaps
from orbitroute.perception.graph import RoadGraph, build_road_graph
from orbitroute.perception.segment import segment_roads
from orbitroute.pipeline import get_sample

STREETS = {"motorway", "trunk", "primary", "secondary", "tertiary", "unclassified", "residential", "living_street"}
TOL_M = 15


def measure(graph: RoadGraph, osm: dict, meta: dict) -> dict:
    W, H, mpp = meta["width_px"], meta["height_px"], meta["m_per_px"]
    x0, y0, x1, y1 = meta["bbox_mercator"]

    def px(lon: float, lat: float) -> tuple[float, float]:
        x, y = to_mercator(lon, lat)
        return (x - x0) / (x1 - x0) * W, (y1 - y) / (y1 - y0) * H

    def raster(lines) -> np.ndarray:
        im = Image.new("L", (W, H), 0)
        d = ImageDraw.Draw(im)
        for pts in lines:
            d.line(pts, fill=255, width=1)
        return np.asarray(im) > 0

    O = raster([[px(p["lon"], p["lat"]) for p in el["geometry"]] for el in osm["elements"] if "geometry" in el and el.get("tags", {}).get("highway") in STREETS])
    any_way = raster([[px(p["lon"], p["lat"]) for p in el["geometry"]] for el in osm["elements"] if "geometry" in el and el.get("tags", {}).get("highway")])
    seen = [e for e in graph.edges if not e.bridge]
    G = raster([[tuple(graph.nodes[e.u]), tuple(graph.nodes[e.v])] for e in graph.edges])
    d_graph = distance_transform_edt(~G) * mpp
    d_any = distance_transform_edt(~any_way) * mpp
    links = [e for e in graph.edges if e.bridge and e.length_m > MIN_LINK_M]
    on_road = 0
    for e in links:
        pts = np.linspace(graph.nodes[e.u], graph.nodes[e.v], max(int(e.length_m / 3), 3))
        xs, ys = np.clip(pts[:, 0].astype(int), 0, W - 1), np.clip(pts[:, 1].astype(int), 0, H - 1)
        on_road += (d_any[ys, xs] <= TOL_M).mean() >= 0.7
    return {
        "graph_km": graph.stats["road_km"], "long_links": len(links), "links_km": round(sum(e.length_m for e in links) / 1000, 2),
        "links_on_a_mapped_road": int(on_road), "recall": float((d_graph[O] <= TOL_M).mean()), "precision": float((d_any[G] <= TOL_M).mean()),
        "seen_edges": len(seen),
    }


def main() -> None:
    names = sys.argv[1:] or ["columbus", "memphis", "houston-harvey", "houston-harvey-b"]
    s = Settings.load()
    guard = BudgetGuard(s.budget_state_path, s.budget_hard_cap_usd, True)
    client = MetaClient(s, guard)
    run = guard.new_run(1.0)
    rows = []
    for name in names:
        sm = get_sample(name)
        osm = json.loads((ROOT / "data" / "cache" / f"osm_{name}.json").read_text())
        mask = segment_roads(client, sm.image_bytes, run=run)
        before_g = build_road_graph(mask, sm.meta["m_per_px"])
        res = fill_gaps(client, sm.image_bytes, mask, before_g, run=run)
        after_g = build_road_graph(res.mask, sm.meta["m_per_px"])
        rows.append({"sample": name, "looked": res.looked, "confirmed": res.confirmed, "before": measure(before_g, osm, sm.meta), "after": measure(after_g, osm, sm.meta)})
        print(name, res.looked, res.confirmed, rows[-1]["before"]["long_links"], "->", rows[-1]["after"]["long_links"], f"spent ${run.spent:.3f}", flush=True)
    out = ROOT / "eval"
    (out / "gaps.json").write_text(json.dumps(rows, indent=1))
    lines = [
        "# A second look at bridged gaps", "",
        "Generated by `scripts/eval_gaps.py`. The graph builder bridges holes in the SAM road mask with straight links. Links over 30 m get a closer look",
        "(a crop around the link goes to SAM again). A confirmed link becomes real road; the rest stay as guesses and are marked as unconfirmed in the plan.",
        "OpenStreetMap (© OpenStreetMap contributors, ODbL) is the yardstick only: \"on a mapped road\" = at least 70% of the link within 15 m of any mapped way.", "",
        "| Photo | Long links before | Looked at | Confirmed | Long links after | Long links on a mapped road (before / after) | Named-street recall (before / after) | Precision (before / after) |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        b, a = r["before"], r["after"]
        lines.append(
            f"| {r['sample']} | {b['long_links']} | {r['looked']} | {r['confirmed']} | {a['long_links']} | {b['links_on_a_mapped_road']}/{b['long_links']} / {a['links_on_a_mapped_road']}/{a['long_links']}"
            f" | {b['recall']:.0%} / {a['recall']:.0%} | {b['precision']:.0%} / {a['precision']:.0%} |"
        )
    lines += ["", f"Cost of this run: about ${run.spent:.2f}. Limits: four photos, OSM is incomplete and of another date.", ""]
    (out / "GAPS.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
