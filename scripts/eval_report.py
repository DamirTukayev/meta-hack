"""Turn eval/results.json into eval/RESULTS.md (the numbers quoted in the README)."""

import json
from pathlib import Path

res = json.loads(Path("eval/results.json").read_text())
out = ["# OrbitRoute evaluation", "", "Generated by `scripts/run_eval.py` + `scripts/eval_report.py`. All numbers come from real runs of the pipeline; nothing is hand-edited.", ""]

if "scenarios" in res:
    s, rows = res["scenarios"]["summary"], res["scenarios"]["rows"]
    b, a, m = s["baseline"], s["agent"], s["model_decider"]
    out += [
        f"## Plan → verify → repair vs. a plain solver ({s['scenarios']} scenarios)",
        "",
        "Baseline = the first solve of the same solver, returned as is (what a pipeline without the verifier would output). "
        "Every plan is audited by the independent verifier, so the baseline's hidden violations become visible.",
        "",
        "| | Solver only (no verifier) | OrbitRoute agent |",
        "|---|---|---|",
        f"| Plans the solver reports as feasible | {b['solver_says_feasible']}/{s['scenarios']} | — |",
        f"| Of those, plans that break a constraint on independent audit | **{b['invalid_after_independent_audit']}** ({(b['invalid_rate_among_claimed_feasible'] or 0):.0%}) | 0 — every plan returned as verified passed the audit |",
        f"| Scenarios with a first-pass violation → ended verified | — | {a['of_those_ended_verified']}/{a['scenarios_with_a_first_pass_violation']} (including those that leave cut-off orders out with a reason; the other {a['scenarios_with_a_first_pass_violation'] - a['of_those_ended_verified']} cannot be met as stated; see the tables) |",
        f"| Provably infeasible requests flagged with a verified fix | 0/{a['provably_infeasible']} (solver returns a plan anyway) | {a['infeasible_correctly_flagged']}/{a['provably_infeasible']} |",
        f"| Final status | — | {', '.join(f'{k}: {v}' for k, v in a['status_counts'].items())} |",
        f"| Mean iterations / mean wall time | 1 | {a['mean_iterations']} / {a['mean_seconds']} s |",
        "",
        f"Violation kinds seen in first-pass plans (scenarios affected): {', '.join(f'{k} {v}' for k, v in b['violation_kinds_in_scenarios'].items()) or 'none'}.",
        "",
    ]
    if m["runs"]:
        same = sum(r["model_decider"]["actions"] == r["agent_actions"] for r in rows if "model_decider" in r)
        rest = m["runs"] - m["reached_verified"]
        out += [
            f"Muse Spark as the repair planner (instead of the deterministic policy), on {m['runs']} scenarios with a first-pass violation: "
            f"it chose exactly the policy's actions in {same}/{m['runs']} runs and {m['reached_verified']}/{m['runs']} ended verified"
            + (f" ({rest} flagged as infeasible as stated)" if rest else "")
            + f"; mean cost ${m['mean_cost_usd']} per run. In this suite the model adds readable reasons, not different decisions.",
            "",
        ]
    def family(r: dict) -> str:
        if "-grid-" in r["id"]:
            return "Drawn zone, orders only where a legal route can reach them"
        if "-any-" in r["id"]:
            return "Drawn zone, orders placed anywhere (some are cut off by the zone)"
        return "Zones found by Muse Spark, plus provably infeasible requests"

    out += ["By kind of scenario (the first family is easy for a plain solver by construction; the second is how a user clicking freely on the map behaves):", "", "| Scenario family | Scenarios | Solver's first plan breaks a rule | Agent: verified | Agent: verified, cut-off orders left out with reasons | Agent: cannot be met as stated (verified fix offered) |", "|---|---|---|---|---|---|"]
    for name in dict.fromkeys(family(r) for r in rows):
        grp = [r for r in rows if family(r) == name]
        st = lambda k: sum(r["agent_status"] == k for r in grp)
        out.append(f"| {name} | {len(grp)} | {sum(not r['baseline_audit_ok'] for r in grp)} | {st('verified')} | {st('verified_partial')} | {st('needs_relaxation')} |")
    out.append("")
    out += ["| Scenario | Request | Solver only | Agent | Iterations | Repairs |", "|---|---|---|---|---|---|"]
    for r in rows:
        base = "ok" if r["baseline_audit_ok"] else "violates " + "+".join(r["baseline_violations"])
        out.append(f"| {r['id']} | {r['orders']} orders, {r['trucks']} trucks, by {r['deadline']}, avoid {'+'.join(r['avoid'])} | {base} | {r['agent_status']} | {r['agent_iterations']} | {', '.join(r['agent_actions']) or '—'} |")
    out.append("")

parse_keys = [k for k in res if k.startswith("parsing")]
if parse_keys:
    n = res[parse_keys[0]]["cases"]
    out += [
        f"## Request parsing ({n} free-form phrasings), by model and prompt version",
        "",
        "| Model | Request prompt | Exact match | Field accuracy | Mean latency | Cost |",
        "|---|---|---|---|---|---|",
    ]
    for k in parse_keys:
        p = res[k]
        provider = "Muse Spark Open (open weights, Baseten)" if "baseten" in k else "Muse Spark 1.3 (Meta API)"
        version = k.rsplit("_", 1)[-1] if k.rsplit("_", 1)[-1].startswith("v") else "v1"
        out.append(f"| {provider} | {version} | {p['exact_match_cases']}/{p['cases']} | {p['field_accuracy']:.1%} | {p['mean_seconds']} s | ${p['cost_usd']} |")
    out += ["", "Prompt v2 states the field rules explicitly (default objective, what counts as a capacity, how to read a time range). It fixed every miss of the open-weight model (11/20 -> 20/20) without hurting the Meta model.", "- Limitation: the cases are written by the project author, so this measures robustness to paraphrase, not to the wild.", ""]
    for k in parse_keys:
        for f in res[k]["failures"]:
            out.append(f"- `{k}`: `{f['text']}` — {f['error'] or ', '.join(f'{a}: expected {v[0]}, got {v[1]}' for a, v in f['wrong'].items())}")
    out.append("")

out.append(f"Evaluation cost: ${res.get('eval_cost_usd', 0)}")
Path("eval/RESULTS.md").write_text("\n".join(out) + "\n")
print("wrote eval/RESULTS.md")
