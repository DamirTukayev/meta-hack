"""Parse the harder phrasings on every model that is set up. Usage: uv run python scripts/eval_parse_hard.py  ->  eval/PARSING_HARD.md"""

import orbitroute.api as api
import orbitroute.eval.runner as runner
from orbitroute.config import ROOT
from orbitroute.eval.parse_hard import HARD_CASES
from orbitroute.llm.client import MetaClient, guard_for

runner.CASES = HARD_CASES  # the runner reads the module-level list
s = api.settings
clients = {"Muse Spark 1.3 (Meta API)": (api.get_client(), api.guard)}
for p, label in (("baseten", "Muse Spark Open (Baseten)"), ("modal", "Muse Spark Open (Modal)")):
    if p in api.text_provider_order():
        g = guard_for(s, p)
        clients[label] = (MetaClient(s, g, provider=p), g)
lines = ["# Request parsing: harder phrasings", "", f"Generated by `scripts/eval_parse_hard.py`: {len(HARD_CASES)} phrasings with capital letters, odd time words (half past, quarter to, 17h), other units, stray detail and no time at all.", "",
         "| Model | Exact match | Field accuracy | Mean latency | Cost |", "|---|---|---|---|---|"]
misses = []
for label, (client, guard) in clients.items():
    res = runner.run_parse_eval(client, guard, log=lambda *_: None)
    lines.append(f"| {label} | {res['exact_match_cases']}/{res['cases']} | {res['field_accuracy']:.1%} | {res['mean_seconds']} s | ${res['cost_usd']} |")
    misses += [f"- {label}: `{f['text']}` — {f['wrong']}" for f in res.get("failures", [])]
    print(label, res["exact_match_cases"], "/", res["cases"], flush=True)
lines += ["", *(["Misses:", "", *misses] if misses else ["No misses."]), "", "Limitation: the phrasings are written by the project author.", ""]
(ROOT / "eval" / "PARSING_HARD.md").write_text("\n".join(lines))
print("\n".join(lines))
