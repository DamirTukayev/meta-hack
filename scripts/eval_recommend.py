"""Does Muse Spark recommend what the rules would, and never the unsafe option?

Runs the cut-off scenarios of the evaluation suite to the point where the agent offers alternatives, then asks the model to
recommend one (on each open-weight provider that is set up, and on the Meta API) and compares with the rules.
Usage: uv run python scripts/eval_recommend.py     ->  eval/RECOMMEND.md
"""

from __future__ import annotations

import json
from collections import Counter

import orbitroute.api as api
from orbitroute.agent.loop import run_agent
from orbitroute.agent.repair import ModelDecider, PolicyDecider, breaks_a_rule
from orbitroute.config import ROOT
from orbitroute.eval.runner import build_scenario, load_world
from orbitroute.eval.scenarios import SCENARIOS
from orbitroute.llm.client import MetaClient, guard_for


def main() -> None:
    s = api.settings
    meta = api.get_client()
    clients = {"Muse Spark 1.3 (Meta API)": meta}
    for p, label in (("baseten", "Muse Spark Open (Baseten)"), ("modal", "Muse Spark Open (Modal)")):
        if p in api.text_provider_order():
            clients[label] = MetaClient(s, guard_for(s, p), provider=p)
    worlds, cases = {}, []
    for sc in SCENARIOS:
        if sc.sample not in worlds:
            worlds[sc.sample] = load_world(meta, sc.sample, api.guard.new_run(3.0))
        scenario = build_scenario(worlds[sc.sample], sc)
        res = run_agent(scenario, decider=PolicyDecider(), time_limit_s=1.5)
        if res.status == "needs_relaxation" and len(res.relaxations) > 1:
            cases.append((sc.id, scenario.problem, res.relaxations, res.recommendation))
    print(len(cases), "scenarios with several verified alternatives")
    out = {"cases": len(cases), "providers": {}}
    for label, client in clients.items():
        run = api.guard.new_run(2.0)
        decider = ModelDecider(client, run)
        same = unsafe = from_model = 0
        picks = Counter()
        for _sid, problem, options, policy_rec in cases:
            rec = decider.recommend(options, problem)
            same += rec.index == policy_rec.index
            from_model += rec.source == "model"
            unsafe += any(not breaks_a_rule(o) for o in options) and breaks_a_rule(options[rec.index])
            picks[options[rec.index].kind] += 1
        out["providers"][label] = {"same_as_rules": same, "answered_by_model": from_model, "unsafe": unsafe, "cost_usd": round(run.spent, 4), "picks": dict(picks)}
        print(label, out["providers"][label], flush=True)
    lines = ["# Recommendation: model against rules", "", f"Generated by `scripts/eval_recommend.py` on the {len(cases)} evaluation scenarios that end with several verified alternatives.", "",
             "| Model | Chose the same option as the rules | Answer came from the model (not the fallback) | Recommended driving through a forbidden zone although a safe option existed | Cost |", "|---|---|---|---|---|"]
    for label, v in out["providers"].items():
        lines.append(f"| {label} | {v['same_as_rules']}/{len(cases)} | {v['answered_by_model']}/{len(cases)} | {v['unsafe']} | ${v['cost_usd']} |")
    lines += ["", "What the model picked: " + "; ".join(f"{label}: {v['picks']}" for label, v in out["providers"].items()), ""]
    (ROOT / "eval" / "RECOMMEND.md").write_text("\n".join(lines))
    json.dump(out, open(ROOT / "eval" / "recommend.json", "w"), indent=1)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
