"""Parse the same ten requests written in English, Russian, Spanish, French, German and Portuguese on every model that is set up
(about $0.2 in all). Usage: uv run python scripts/eval_parse_languages.py  ->  eval/PARSING_LANGUAGES.md"""

import orbitroute.api as api
import orbitroute.eval.runner as runner
from orbitroute.config import ROOT
from orbitroute.eval.parse_languages import TEXTS, cases
from orbitroute.llm.client import MetaClient, guard_for

s = api.settings
clients = {"Muse Spark 1.3 (Meta API)": (api.get_client(), api.guard)}
for p, label in (("baseten", "Muse Spark Open (Baseten)"), ("modal", "Muse Spark Open (Modal)")):
    if p in api.text_provider_order():
        g = guard_for(s, p)
        clients[label] = (MetaClient(s, g, provider=p), g)
rows, misses, spent = {}, [], 0.0
for label, (client, guard) in clients.items():
    for language in TEXTS:
        runner.CASES = cases(language)  # the runner reads the module-level list
        res = runner.run_parse_eval(client, guard, log=lambda *_: None)
        rows[(label, language)] = res
        spent += res["cost_usd"]
        misses += [f"- {label}, {language}: `{f['text']}` — {f['wrong']}" for f in res.get("failures", [])]
        print(label, language, res["exact_match_cases"], "/", res["cases"], flush=True)
lines = [
    "# Request parsing in six languages", "",
    "Generated by `scripts/eval_parse_languages.py`: the same ten requests (deadline, trucks, orders, what to avoid, start time, minutes per stop, no time at all) written in English, Russian, Spanish, French, German and Portuguese,",
    "with the same expected constraints. An exact match means every field was read as expected.", "",
    "| Model | " + " | ".join(TEXTS) + " |", "|---|" + "---|" * len(TEXTS),
]
for label in clients:
    lines.append(f"| {label} | " + " | ".join(f"{rows[(label, lang)]['exact_match_cases']}/{rows[(label, lang)]['cases']}" for lang in TEXTS) + " |")
lines += ["", *(["Misses:", "", *misses] if misses else ["No misses."]), "", f"Cost of this run: about ${spent:.2f}. Limitation: the requests are written by the project author, ten per language; the answers to the interface itself (agent log, assumptions, repair options) are still in English.", ""]
(ROOT / "eval" / "PARSING_LANGUAGES.md").write_text("\n".join(lines))
print("\n".join(lines))
