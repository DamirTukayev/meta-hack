"""Compare the versions of the scene prompt on real model runs (costs about $0.07 per version) and write
eval/grounding.json and eval/GROUNDING.md.

Usage: uv run python scripts/eval_grounding.py [--repeats 3]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from orbitroute.config import Settings
from orbitroute.eval.grounding import run_grounding_eval
from orbitroute.llm.budget import BudgetGuard
from orbitroute.llm.client import MetaClient
from orbitroute.prompts import active_version

SAMPLES = ["columbus", "memphis"]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repeats", type=int, default=3)
    a = ap.parse_args()
    s = Settings.load()
    guard = BudgetGuard(s.budget_state_path, s.budget_hard_cap_usd, s.paid_calls_enabled)
    res = run_grounding_eval(MetaClient(s, guard), guard, SAMPLES, a.repeats)
    Path("eval").mkdir(exist_ok=True)
    Path("eval/grounding.json").write_text(json.dumps(res, indent=1))

    out = [
        "# Scene grounding: prompt versions compared",
        "",
        f"Generated by `scripts/eval_grounding.py`. Each version asks Muse Spark about the same {len(SAMPLES)} images {res['repeats']} times.",
        "There are no human-labelled zones, so this measures **stability** (how much repeated answers agree), **structure** (zones of different kinds should not overlap) and a **vegetation sanity check** (park/forest zones should be greener than built-up ones), not accuracy.",
        "",
        f"Active version: `{active_version('scene')}`.",
        "",
        "| Version | Image | Stability (mean / worst pair) | Zones per run | Outlined share | Overlapping share | Cost |",
        "|---|---|---|---|---|---|---|",
    ]
    for v, d in res["versions"].items():
        for name, m in d["samples"].items():
            out.append(f"| {v} | {name} | {m['stability']:.0%} / {m['stability_min']:.0%} | {m['zones_per_run']} | {m['covered_share']:.0%} | {m['overlap_share']:.0%} | ${d['cost_usd']} (all images) |")
    out += ["", "Excess-green index by zone kind (higher = more vegetation):", ""]
    for v, d in res["versions"].items():
        for name, m in d["samples"].items():
            out.append(f"- `{v}` {name}: " + ", ".join(f"{k} {x:+.0f}" for k, x in m["excess_green_by_kind"].items()))
    Path("eval/GROUNDING.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
