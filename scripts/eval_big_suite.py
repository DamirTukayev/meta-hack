"""A larger scenario suite: hundreds of random scenarios over the four bundled photos, no paid calls.

Each scenario draws a random square zone (150-500 px, anywhere on the photo), 8-60 orders (placed at buildings where
SAM found them, either only where a legal route reaches or anywhere), 1-6 trucks, a deadline, sometimes a stated capacity.
On the Houston photos the water SAM found is avoided as well. The agent runs with the deterministic policy (no model
calls). The independent audit judges every plan, first and returned. Only cached SAM/scene answers are used.
Writes eval/BIG_SUITE.md and eval/big_suite.json.

Usage: uv run python scripts/eval_big_suite.py [N=300] [--seed 7]
"""

from __future__ import annotations

import json
import random
import sys
import time
from collections import Counter
from statistics import mean

from orbitroute.agent.loop import run_agent
from orbitroute.agent.repair import PolicyDecider
from orbitroute.config import ROOT, Settings
from orbitroute.eval.runner import build_scenario, load_world
from orbitroute.eval.scenarios import EvalScenario
from orbitroute.llm.budget import BudgetGuard
from orbitroute.llm.client import MetaClient
from orbitroute.verifier.independent import audit_plan, disagreements

PHOTOS = ["columbus", "memphis", "houston-harvey", "houston-harvey-b"]
DEADLINES = ["10:00", "11:00", "12:00", "13:00", "15:00"]


def draw(rng: random.Random, i: int) -> EvalScenario:
    photo = PHOTOS[i % len(PHOTOS)]
    size = rng.uniform(150, 500)
    x, y = rng.uniform(0, 1536 - size), rng.uniform(0, 1536 - size)
    flood = photo.startswith("houston") and rng.random() < 0.5
    return EvalScenario(
        f"big-{i:03d}", photo, rng.randint(8, 60), rng.randint(1, 6), rng.choice(DEADLINES), ("flooded",) if flood else (),
        seed=rng.randint(0, 99), capacity=rng.choice([None, None, 10, 15, 25]),
        zone=((x, y), (x + size, y), (x + size, y + size), (x, y + size)), anywhere=rng.random() < 0.5,
    )


def main() -> None:
    n = int(sys.argv[1]) if len(sys.argv) > 1 and sys.argv[1].isdigit() else 300
    seed = int(sys.argv[sys.argv.index("--seed") + 1]) if "--seed" in sys.argv else 7
    s = Settings.load()
    guard = BudgetGuard(s.budget_state_path, s.budget_hard_cap_usd, False)  # cached answers only: a paid call would raise
    client = MetaClient(s, guard)
    run = guard.new_run(1.0)
    worlds = {p: load_world(client, p, run) for p in PHOTOS}
    rng = random.Random(seed)
    rows, refused = [], Counter()
    t0 = time.perf_counter()
    for i in range(n):
        sc = draw(rng, i)
        try:
            scenario = build_scenario(worlds[sc.sample], sc)
        except ValueError as exc:  # e.g. not enough room for that many orders: refused with a message, not a crash
            refused[str(exc)[:60]] += 1
            continue
        res = run_agent(scenario, decider=PolicyDecider(), time_limit_s=1.0)
        first = res.iterations[0]
        a_first = audit_plan(scenario, first.plan, excluded={})
        a_final = audit_plan(res.scenario, res.plan, excluded=res.report.excluded)
        rows.append({
            "id": sc.id, "photo": sc.sample, "orders": sc.n_orders, "trucks": sc.n_vehicles, "anywhere": sc.anywhere,
            "solver_feasible": first.plan.feasible, "first_plan_valid": a_first.ok, "status": res.status,
            "final_ok": res.report.ok, "final_audit_ok": a_final.ok, "iterations": len(res.iterations),
            "disagreements": len(disagreements(first.report, a_first)) + len(disagreements(res.report, a_final)),
            "seconds": round(res.seconds, 1),
        })
        if (i + 1) % 25 == 0:
            print(f"{i + 1}/{n} {time.perf_counter() - t0:.0f}s", flush=True)

    m = len(rows)
    claimed = [r for r in rows if r["solver_feasible"]]
    bad_first = [r for r in claimed if not r["first_plan_valid"]]
    returned = [r for r in rows if r["status"] in ("verified", "verified_partial")]
    summary = {
        "drawn": n, "ran": m, "refused": dict(refused),
        "solver_called_the_first_plan_feasible": len(claimed),
        "of_those_broke_a_rule_per_audit": len(bad_first),
        "statuses": dict(Counter(r["status"] for r in rows)),
        "returned_plans_failing_the_audit": sum(not r["final_audit_ok"] for r in returned),
        "verifier_audit_disagreements": sum(r["disagreements"] for r in rows),
        "mean_iterations": round(mean(r["iterations"] for r in rows), 2),
        "mean_seconds": round(mean(r["seconds"] for r in rows), 1),
    }
    by_photo = {p: [r for r in rows if r["photo"] == p] for p in PHOTOS}
    out = ROOT / "eval"
    (out / "big_suite.json").write_text(json.dumps({"summary": summary, "rows": rows}, indent=1))
    lines = [
        "# A larger scenario suite", "",
        f"Generated by `scripts/eval_big_suite.py` (seed {seed}): {n} random scenarios over the four bundled photos, {m} ran. Each draws a random",
        "square zone, 8-60 orders (at buildings, either only where a legal route reaches or anywhere), 1-6 trucks, a deadline and sometimes a",
        "stated capacity; on the Houston photos half also avoid the standing water. The agent used the deterministic policy: no model calls, no cost.",
        "Every plan, the first and the returned one, was judged by the independent audit (`verifier/independent.py`).", "",
        "| | |", "|---|---|",
        f"| Scenarios that ran | {m} (refused with a message: {sum(refused.values())}) |",
        f"| Solver called its first plan feasible | {len(claimed)} |",
        f"| ...of those, broke a rule (audit) | {len(bad_first)} ({len(bad_first) / max(len(claimed), 1):.0%}) |",
        f"| Outcomes | {', '.join(f'{k}: {v}' for k, v in sorted(summary['statuses'].items()))} |",
        f"| Returned (verified) plans that fail the audit | {summary['returned_plans_failing_the_audit']} of {len(returned)} |",
        f"| Verifier vs audit disagreements | {summary['verifier_audit_disagreements']} over {2 * m} plans |",
        f"| Mean iterations / seconds | {summary['mean_iterations']} / {summary['mean_seconds']} |", "",
        "| Photo | Scenarios | First plan broke a rule | Ended verified | Needed relaxation |", "|---|---|---|---|---|",
        *[
            f"| {p} | {len(r)} | {sum(not x['first_plan_valid'] for x in r if x['solver_feasible'])} | {sum(x['status'] in ('verified', 'verified_partial') for x in r)} | {sum(x['status'] == 'needs_relaxation' for x in r)} |"
            for p, r in by_photo.items()
        ], "",
        "Limits: the scenarios are random, not real requests; the audit and the verifier were written by the same author; the roads are the ones SAM found.", "",
    ]
    (out / "BIG_SUITE.md").write_text("\n".join(lines))
    print(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
