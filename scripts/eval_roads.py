"""How good is the road graph? Compare it with OpenStreetMap on the bundled samples.

OpenStreetMap is used only as a yardstick here (© OpenStreetMap contributors, ODbL); it is not part of the product and
the raw download is cached under data/cache, which is not committed. The graph comes from the cached SAM masks, so this
makes no paid calls.

Usage: uv run python scripts/eval_roads.py [columbus memphis]  ->  eval/ROADS.md, eval/roads.json
"""

from __future__ import annotations

import json
import subprocess
import sys
import time
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw
from scipy.ndimage import distance_transform_edt

from orbitroute.config import ROOT, Settings
from orbitroute.llm.budget import BudgetGuard
from orbitroute.llm.client import MetaClient
from orbitroute.naip import to_mercator
from orbitroute.perception.graph import build_road_graph
from orbitroute.perception.segment import segment_concept
from orbitroute.pipeline import get_sample

CACHE = ROOT / "data" / "cache"
STREETS = {"motorway", "trunk", "primary", "secondary", "tertiary", "unclassified", "residential", "living_street"}
HIDDEN_SERVICE = {"parking_aisle", "driveway", "drive-through"}
TOLERANCES_M = (8, 15)
OVERPASS = ("https://overpass-api.de/api/interpreter", "https://overpass.private.coffee/api/interpreter")


def fetch_osm(name: str, bbox: list[float]) -> dict:
    path = CACHE / f"osm_{name}.json"
    if path.exists():
        return json.loads(path.read_text())
    w, s, e, n = bbox
    query = f'[out:json][timeout:50];way["highway"]({s},{w},{n},{e});out geom;'
    CACHE.mkdir(parents=True, exist_ok=True)
    for _ in range(5):
        for url in OVERPASS:
            subprocess.run(["curl", "-s", "-m", "80", "-A", "OrbitRoute-eval/0.1 (hackathon evaluation)", "--data-urlencode", f"data={query}", url, "-o", str(path)])
            try:
                return json.loads(path.read_text())
            except json.JSONDecodeError:
                time.sleep(20)
    raise SystemExit("Overpass did not answer; try again later")


def evaluate(name: str, client: MetaClient, guard: BudgetGuard) -> dict:
    sm = get_sample(name)
    W, H = sm.meta["width_px"], sm.meta["height_px"]
    m_per_px = sm.meta["m_per_px"]
    x0, y0, x1, y1 = sm.meta["bbox_mercator"]
    mask = segment_concept(client, sm.image_bytes, "road", run=guard.new_run(1))
    graph = build_road_graph(mask, m_per_px)
    osm = fetch_osm(name, sm.meta["bbox_lonlat"])

    def px(lon: float, lat: float) -> tuple[float, float]:
        x, y = to_mercator(lon, lat)
        return (x - x0) / (x1 - x0) * W, (y1 - y) / (y1 - y0) * H

    def osm_raster(keep) -> np.ndarray:
        im = Image.new("L", (W, H), 0)
        d = ImageDraw.Draw(im)
        for el in osm["elements"]:
            tags = el.get("tags", {})
            if "geometry" in el and keep(tags):
                d.line([px(p["lon"], p["lat"]) for p in el["geometry"]], fill=255, width=1)
        return np.asarray(im) > 0

    g_im = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(g_im)
    for u, v in graph.to_networkx().edges:
        d.line([tuple(graph.nodes[u]), tuple(graph.nodes[v])], fill=255, width=1)
    G = np.asarray(g_im) > 0
    dist_to_graph = distance_transform_edt(~G) * m_per_px

    rows = []
    for label, keep in [
        ("named streets", lambda t: t.get("highway") in STREETS),
        ("streets + service roads (no parking aisles or driveways)", lambda t: t.get("highway") is not None and t.get("service") not in HIDDEN_SERVICE),
        ("every mapped way, parking aisles and driveways included", lambda t: t.get("highway") is not None),
    ]:
        O = osm_raster(keep)
        dist_to_osm = distance_transform_edt(~O) * m_per_px
        for tol in TOLERANCES_M:
            rows.append(
                {
                    "reference": label,
                    "tolerance_m": tol,
                    "recall": float((dist_to_graph[O] <= tol).mean()),
                    "precision": float((dist_to_osm[G] <= tol).mean()),
                    "osm_km": round(float(O.sum()) * m_per_px / 1000, 1),
                }
            )
    return {"sample": name, "graph_km": graph.stats["road_km"], "dropped_km": graph.stats["dropped_road_km"], "rows": rows}


def main() -> None:
    names = sys.argv[1:] or ["columbus", "memphis"]
    s = Settings.load()
    guard = BudgetGuard(s.budget_state_path, s.budget_hard_cap_usd, False)  # cache only: no paid calls
    client = MetaClient(s, guard)
    results = [evaluate(n, client, guard) for n in names]
    out = ROOT / "eval"
    (out / "roads.json").write_text(json.dumps(results, indent=1))
    lines = [
        "# Road graph accuracy",
        "",
        "Generated by `scripts/eval_roads.py`. The road graph that SAM 3.1 produces (the only roads the agent routes on) is compared with OpenStreetMap",
        "as a yardstick (© OpenStreetMap contributors, ODbL; used for measurement only, not part of the product).",
        "",
        "- **Precision**: share of the graph's length that lies within the tolerance of an OSM road (is the graph real?). Read it against the last reference:",
        "  SAM also finds paved lot aisles and driveways that really exist and that OSM tags as parking aisles, so precision against named streets alone understates it.",
        "- **Recall**: share of the OSM road length that lies within the tolerance of the graph (how much of the street network did the agent find?).",
        "",
    ]
    for r in results:
        lines += [f"## {r['sample']}  (graph {r['graph_km']} km kept, {r['dropped_km']} km dropped as disconnected)", "", "| OSM reference | Tolerance | Precision | Recall | OSM length |", "|---|---|---|---|---|"]
        lines += [f"| {x['reference']} | {x['tolerance_m']} m | {x['precision']:.0%} | {x['recall']:.0%} | {x['osm_km']} km |" for x in r["rows"]]
        lines.append("")
    lines += [
        "Limits: two 1.5 km tiles only. OSM is itself incomplete and the imagery and OSM are from different dates, so recall is a lower bound on the",
        "true share of streets found. Parking aisles, driveways and alleys are mostly invisible to SAM at this resolution, which is why the second reference",
        "(which includes service roads) has a lower recall. The graph keeps only the largest connected component of what SAM found.",
        "",
    ]
    (out / "ROADS.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
