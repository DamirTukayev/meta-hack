"""Does flood detection work beyond Hurricane Harvey? SAM 3.1 on NOAA photos from other disasters, plus dry controls.

Each place is a 1.5 km square of NOAA Emergency Response Imagery (public domain) from the days after a storm. The same
two prompts the app uses (`flooded area`, `flood water`) are run on it and the water SAM finds is drawn over the photo.
There are no ground-truth labels: the "Verdict" column is the author's reading of the contact sheet, and the sheet itself
(`docs/flood-events.jpg`, photo on the left and water on the right) lets anyone check it. Costs about $0.08 per new photo.
Writes eval/FLOOD_EVENTS.md and docs/flood-events.jpg.

Usage: uv run python scripts/eval_flood_events.py [--budget 1.5]
"""

from __future__ import annotations

import io
import sys

from PIL import Image, ImageDraw

from orbitroute.config import ROOT, Settings
from orbitroute.llm.budget import BudgetGuard
from orbitroute.llm.client import MetaClient
from orbitroute.perception.flood import flood_zones, segment_floods
from orbitroute.storm import fetch_storm_tile

# (key, dataset, lon, lat, label, what the photo shows: the author's reading, filled from the contact sheet)
PLACES = [
    ("harvey-a", "20170830-rgb", -95.69697, 29.77224, "Houston TX, Harvey (flooded streets)", "flooded streets and yards: the water is found along them"),
    ("lumberton", "20180919c-rgb", -79.01, 34.62, "Lumberton NC, Florence", "flooded woods and an underpass at the edge of town: found"),
    ("lumberton-sw", "20180919c-rgb", -79.025, 34.600, "Lumberton NC south-west, Florence", "farmland: a few small pools found"),
    ("newbern", "20180919a-rgb", -77.04, 35.10, "New Bern NC, Florence", "river and harbour (permanent water): found, but with blocky edges"),
    ("fmshores", "20220930b-rgb", -81.77, 26.66, "Fort Myers Shores FL, Ian", "ponds and flooded lots among dry roads: found"),
    ("iona", "20220930d-rgb", -81.92, 26.52, "Iona FL, Ian", "ponds and canals found, the wet meadow is not"),
    ("capecoral", "20220930d-rgb", -81.97, 26.60, "Cape Coral FL, Ian", "dry streets; canals (permanent water) found only in part"),
    ("fortmyers", "20220930d-rgb", -81.95, 26.45, "Fort Myers Beach FL, Ian", "gulf and canals (permanent water): found in blocks, with gaps"),
    ("kerrville", "20250712a-rgb", -99.14, 30.05, "Kerrville TX, July 2025 flood", "dry town, scoured river bed: the channel is found"),
    ("kerrville-river", "20250712a-rgb", -99.145, 30.035, "Kerrville TX river, July 2025", "dry hills, river on the right edge: found"),
    ("swannanoa", "20241005a-rgb", -82.40, 35.60, "Swannanoa NC, Helene", "scoured stream channel and mud: found in part"),
    ("asheville", "20241006a-rgb", -82.575, 35.575, "Asheville NC, Helene", "river on the right edge found; the tree-covered streets are dry"),
]


def main() -> None:
    budget = float(sys.argv[sys.argv.index("--budget") + 1]) if "--budget" in sys.argv else 1.5
    s = Settings.load()
    guard = BudgetGuard(s.budget_state_path, s.budget_hard_cap_usd, True)
    client = MetaClient(s, guard)
    run = guard.new_run(budget)
    cache = ROOT / "data" / "cache" / "events"
    cache.mkdir(parents=True, exist_ok=True)

    rows, panels = [], []
    for key, dataset, lon, lat, label, reading in PLACES:
        path = cache / f"{key}.jpg"
        if not path.exists():
            data, _ = fetch_storm_tile(dataset, lon, lat, span_m=1500, px=1536)
            path.write_bytes(data)
        image_bytes = path.read_bytes()
        mpp = 1500 / 1536
        mask = segment_floods(client, image_bytes, run=run)
        zones = flood_zones(mask, mpp)
        covered = sum(z.polygon.area for z in zones) / (1536 * 1536)
        rows.append((label, dataset, len(zones), covered, reading))

        photo = Image.open(io.BytesIO(image_bytes)).convert("RGB")
        over = photo.copy()
        draw = ImageDraw.Draw(over, "RGBA")
        for z in zones:
            draw.polygon(list(z.polygon.exterior.coords), fill=(0, 200, 255, 110), outline=(0, 230, 255, 255))
        pair = Image.new("RGB", (800, 400))
        pair.paste(photo.resize((400, 400)), (0, 0))
        pair.paste(over.resize((400, 400)), (400, 0))
        ImageDraw.Draw(pair).text((8, 8), label, fill="yellow")
        panels.append(pair)
        print(f"{label}: {len(zones)} patches, {covered:.0%} of the photo (${run.spent:.3f} so far)", flush=True)

    cols = 2
    sheet = Image.new("RGB", (800 * cols, 400 * ((len(panels) + cols - 1) // cols)))
    for i, p in enumerate(panels):
        sheet.paste(p, ((i % cols) * 800, (i // cols) * 400))
    sheet.save(ROOT / "docs" / "flood-events.jpg", quality=72)

    lines = [
        "# Flood detection beyond Hurricane Harvey",
        "",
        "Generated by `scripts/eval_flood_events.py`: the app's two flood prompts (SAM 3.1) on 1.5 km squares of NOAA Emergency Response Imagery",
        "(public domain) from five other disasters, plus places where the water is permanent or absent. The sheet `docs/flood-events.jpg` shows",
        "each photo (left) and the water found (right). There are no ground-truth labels: the last column is the author's reading of the photo.",
        "",
        "| Place | Dataset | Water patches | Share of photo | What the photo shows |",
        "|---|---|---|---|---|",
        *[f"| {a} | `{b}` | {c} | {d:.0%} | {e} |" for a, b, c, d, e in rows],
        "",
        "![Photo and detected water, side by side](../docs/flood-events.jpg)",
        "",
        "Limits: no labels, one square per place; permanent water (canals, harbours, rivers) is also found and avoided, which is the right",
        "thing for a truck but not a flood measurement. Over large open water (New Bern, Fort Myers Beach) the result has blocky edges and gaps",
        "where tiles end, so the share of the photo there is a lower bound; on narrow streets and yards, where trucks actually drive, the outlines follow the visible water in these 12 squares (judged by eye).",
        "Cost: about $0.08 per new photo (answers are cached, so a rerun is free).",
        "",
    ]
    (ROOT / "eval" / "FLOOD_EVENTS.md").write_text("\n".join(lines))
    print("spent", round(run.spent, 3))


if __name__ == "__main__":
    main()
